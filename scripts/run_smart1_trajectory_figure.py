"""Hero trajectory figure of the full SMART-1-class mission (dark, OrbitView-like).

Flies the *single continuous* mission in GMAT headless -- the same trace as
``run_smart1_full_viz`` (Phase-1 Hall spiral from the real GTO out to the lunar
SOI, then the binary-QUBO anti-tangential capture, then a short coast) -- but
instead of opening the GMAT GUI it logs the full position ephemeris at every
integration step and renders a clean, reproducible, publication figure that
looks like the GMAT OrbitView:

  (a) Earth-centred inertial : the iconic apogee-raising spiral expanding from
      GTO to lunar distance and the lunar encounter.
  (b) Moon-centred           : the capture hook -- inbound near-parabola braked
      into a bound lunar orbit, with the lunar sphere of influence marked.

The ephemeris is cached to ``figures/smart1_trajectory.npz`` so the figure can
be regenerated without GMAT via ``--replot``.

Run:  python -m scripts.run_smart1_trajectory_figure
      python -m scripts.run_smart1_trajectory_figure --replot
"""

from __future__ import annotations

import argparse
import re
import subprocess
import tempfile
from pathlib import Path

import numpy as np

from qalunar.highfidelity import find_gmat_console
from scripts import run_smart1_full_viz as viz

FIG_DIR = Path(__file__).resolve().parent / "figures"
EARTH_RADIUS_KM = 6_378.137
MOON_RADIUS_KM = 1_737.4
MOON_SOI_KM = viz.MOON_SOI_KM

# Light "publication" palette (white background, clean for print).
C_BG = "white"
C_EARTH = "#1f5fc0"
C_EARTH_GLOW = "#bcd4ff"
C_MOON = "#8a8f9c"
C_SPIRAL = "#0e7c8b"      # teal -- Earth-bound thrusting spiral
C_CAPTURE = "#d9531e"     # burnt orange -- lunar braking / capture
C_FAINT = "#c2c7d0"
C_TEXT = "#1e2430"


def build_ephem_script(report: str) -> str:
    """Full single-trace mission, logging the position ephemeris each step."""
    sma, ecc = viz._gto()
    cap = "\n".join(viz._capture_segments(viz._capture_schedule()))
    return f"""% Auto-generated by scripts/run_smart1_trajectory_figure.py
% Full SMART-1 mission, single continuous trace; logs X/Y/Z each step.

Create CoordinateSystem MoonView;
MoonView.Origin = Luna;
MoonView.Axes = MJ2000Eq;

Create Spacecraft Sat;
Sat.DateFormat = UTCGregorian;
Sat.Epoch = '{viz.ENCOUNTER_EPOCH}';
Sat.CoordinateSystem = EarthMJ2000Eq;
Sat.DisplayStateType = Keplerian;
Sat.SMA = {sma:.6f};
Sat.ECC = {ecc:.8f};
Sat.INC = {viz.INC_DEG};
Sat.RAAN = 0;
Sat.AOP = 0;
Sat.TA = 0;
Sat.DryMass = {viz.DRY_MASS_KG};
Sat.Tanks = {{XeTank}};
Sat.Thrusters = {{Hall, Brk}};
Sat.PowerSystem = SolarP;

Create ElectricTank XeTank;
XeTank.AllowNegativeFuelMass = false;
XeTank.FuelMass = {viz.XE_LOADED_KG};

Create ElectricThruster Hall;
Hall.CoordinateSystem = Local;
Hall.Origin = Earth;
Hall.Axes = VNB;
Hall.ThrustDirection1 = 1;
Hall.ThrustDirection2 = 0;
Hall.ThrustDirection3 = 0;
Hall.DecrementMass = true;
Hall.Tank = {{XeTank}};
Hall.ThrustModel = ConstantThrustAndIsp;
Hall.ConstantThrust = {viz.THRUST_MN * 1e-3:.6f};
Hall.Isp = {viz.ISP_S};
Hall.MaximumUsablePower = 2;
Hall.MinimumUsablePower = 0.01;

Create ElectricThruster Brk;
Brk.CoordinateSystem = Local;
Brk.Origin = Luna;
Brk.Axes = VNB;
Brk.ThrustDirection1 = -1;
Brk.ThrustDirection2 = 0;
Brk.ThrustDirection3 = 0;
Brk.DecrementMass = true;
Brk.Tank = {{XeTank}};
Brk.ThrustModel = ConstantThrustAndIsp;
Brk.ConstantThrust = {viz.THRUST_MN * 1e-3:.6f};
Brk.Isp = {viz.ISP_S};
Brk.MaximumUsablePower = 2;
Brk.MinimumUsablePower = 0.01;

Create SolarPowerSystem SolarP;
SolarP.InitialMaxPower = 1.9;
SolarP.AnnualDecayRate = 0;
SolarP.Margin = 0;
% Eclipses are neglected in the SMART-1 reproduction: the cached capture
% schedule (smart1_capture.csv) and the 04 Oct 2003 encounter phasing were
% found with continuous power; with DualCone the spiral timing shifts and
% the encounter is lost. State this simplification in the manuscript.
SolarP.ShadowModel = 'None';

Create FiniteBurn Spiral;
Spiral.Thrusters = {{Hall}};
Create FiniteBurn Brake;
Brake.Thrusters = {{Brk}};

Create ForceModel FM;
FM.CentralBody = Earth;
FM.PrimaryBodies = {{Earth}};
FM.GravityField.Earth.Degree = 4;
FM.GravityField.Earth.Order = 4;
FM.PointMasses = {{Luna, Sun}};

Create Propagator Prop;
Prop.FM = FM;
Prop.Type = RungeKutta89;
Prop.InitialStepSize = 60;
Prop.Accuracy = 1e-9;
Prop.MinStep = 0;
Prop.MaxStep = 1800;

Create ReportFile Eph;
Eph.Filename = '{report}';
Eph.Precision = 10;
Eph.WriteHeaders = false;
Eph.Add = {{Sat.ElapsedDays, Sat.EarthMJ2000Eq.X, Sat.EarthMJ2000Eq.Y, Sat.EarthMJ2000Eq.Z, Sat.MoonView.X, Sat.MoonView.Y, Sat.MoonView.Z}};

Create Variable goflag niter;

BeginMissionSequence;

% --- Phase 1: tangential spiral from GTO to the lunar SOI ---
BeginFiniteBurn Spiral(Sat);
goflag = 1;
niter = 0;
While goflag > 0.5
   Propagate Prop(Sat) {{Sat.ElapsedSecs = 43200}};
   niter = niter + 1;
   goflag = 0;
   If Sat.Luna.RMAG > {MOON_SOI_KM:.1f}
      goflag = 1;
   EndIf
   If niter > 320
      goflag = 0;
   EndIf
EndWhile
EndFiniteBurn Spiral(Sat);

% --- Phase 2: anti-tangential binary-QUBO capture braking (finite burns from
% the schedule cached in smart1_capture.csv; no impulsive manoeuvre) ---
{cap}

% --- Phase 3: coast on the resulting bound lunar orbit ---
Propagate Prop(Sat) {{Sat.ElapsedSecs = {viz.POST_COAST_DAYS * 86400.0:.1f}}};
"""


def _generate_ephemeris() -> np.ndarray:
    console = find_gmat_console()
    if not console.exists():
        raise SystemExit(f"GmatConsole not found at {console}")
    report = "smart1_trajectory_ephem.txt"
    script = build_ephem_script(report)
    with tempfile.NamedTemporaryFile("w", suffix=".script", delete=False,
                                     encoding="ascii") as fh:
        fh.write(script)
        tmp = Path(fh.name)
    print("  flying the full mission in GMAT (spiral + capture) ...", flush=True)
    try:
        proc = subprocess.run([str(console), str(tmp)], cwd=str(console.parent),
                              capture_output=True, text=True, timeout=1800)
        raw = (proc.stdout or "") + (proc.stderr or "")
        if not re.search(r"Mission run completed", raw):
            raise SystemExit("GMAT failed:\n" + "\n".join(raw.splitlines()[-25:]))
        for d in (console.parent.parent / "output", console.parent / "output",
                  console.parent):
            p = d / report
            if p.exists():
                rows = [[float(v) for v in ln.split()]
                        for ln in p.read_text().strip().splitlines() if ln.strip()]
                p.unlink(missing_ok=True)
                return np.asarray(rows)
        raise SystemExit(f"ephemeris report {report} not found")
    finally:
        tmp.unlink(missing_ok=True)


def _glow(ax, x, y, color, lw=1.7, n=2, base_alpha=0.05, zorder=3):
    """Draw a line with a soft halo (a couple of faint wide strokes)."""
    for k in range(n, 0, -1):
        ax.plot(x, y, color=color, lw=lw + 2.0 * k, alpha=base_alpha,
                solid_capstyle="round", zorder=zorder)
    ax.plot(x, y, color=color, lw=lw, solid_capstyle="round", zorder=zorder + 1)


def _disk(ax, cx, cy, r, color, glow=None, zorder=6):
    import matplotlib.pyplot as plt
    if glow is not None:
        ax.add_patch(plt.Circle((cx, cy), r * 2.6, color=glow, alpha=0.18,
                                 zorder=zorder - 1, lw=0))
        ax.add_patch(plt.Circle((cx, cy), r * 1.7, color=glow, alpha=0.18,
                                 zorder=zorder - 1, lw=0))
    ax.add_patch(plt.Circle((cx, cy), r, color=color, zorder=zorder, lw=0))


def _style_axes(ax):
    ax.set_facecolor(C_BG)
    ax.set_aspect("equal")
    ax.grid(True, color=C_FAINT, lw=0.5, alpha=0.6)
    ax.set_axisbelow(True)
    for s in ax.spines.values():
        s.set_color("#9aa0ab")
    ax.tick_params(colors=C_TEXT, labelsize=8)
    ax.xaxis.label.set_color(C_TEXT)
    ax.yaxis.label.set_color(C_TEXT)


def _plot(data: np.ndarray) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    days = data[:, 0]
    sat_e = data[:, 1:4]            # sat rel Earth, MJ2000Eq
    sat_m = data[:, 4:7]            # sat rel Luna,  MJ2000Eq
    moon_e = sat_e - sat_m         # Moon rel Earth (same axes)

    fig, (axA, axB) = plt.subplots(1, 2, figsize=(13.0, 6.0))
    fig.patch.set_facecolor(C_BG)

    # ---------- (a) Earth-centred inertial ----------
    # The trace stops at the lunar SOI entry: after the encounter the spacecraft
    # is not held by the Moon, and drawing its Earth-relative path would read as
    # a return to an Earth orbit. Panel (b) shows what happens inside the SOI.
    xe, ye = sat_e[:, 0] * 1e-3, sat_e[:, 1] * 1e-3      # 1000 km units
    mxe, mye = moon_e[:, 0] * 1e-3, moon_e[:, 1] * 1e-3
    _style_axes(axA)
    rm_all = np.linalg.norm(sat_m, axis=1)
    enc = int(np.argmax(rm_all < MOON_SOI_KM))           # first sample inside the SOI
    r_moon = np.hypot(mxe[enc], mye[enc])
    axA.add_patch(plt.Circle((0, 0), r_moon, fill=False, ec=C_FAINT, ls=(0, (6, 6)),
                             lw=1.0, alpha=0.7, zorder=2))
    axA.add_patch(plt.Circle((mxe[enc], mye[enc]), MOON_SOI_KM * 1e-3, fill=False,
                             ec=C_MOON, ls=(0, (3, 3)), lw=0.9, zorder=6))
    _glow(axA, xe[:enc + 1], ye[:enc + 1], C_SPIRAL, lw=1.3, zorder=3)
    _disk(axA, 0, 0, EARTH_RADIUS_KM * 1e-3, C_EARTH, glow=C_EARTH_GLOW, zorder=8)
    _disk(axA, mxe[enc], mye[enc], MOON_RADIUS_KM * 1e-3 * 3.0, C_MOON, zorder=7)
    axA.scatter([xe[0]], [ye[0]], s=24, color=C_TEXT, edgecolors="white",
                lw=0.6, zorder=9)
    axA.annotate("GTO", (xe[0], ye[0]), textcoords="offset points",
                 xytext=(12, 12), color=C_TEXT, fontsize=8, zorder=10,
                 bbox=dict(boxstyle="round,pad=0.2", fc="white", ec="none", alpha=0.85))
    axA.annotate("Moon\n(encounter)", (mxe[enc], mye[enc]),
                 textcoords="offset points", xytext=(10, 6),
                 color=C_TEXT, fontsize=8)
    axA.set_title("(a)  Earth-centred: orbit-raising spiral to the Moon",
                  color=C_TEXT, fontsize=10.5, pad=8)
    axA.set_xlabel("x  ($10^3$ km, Earth MJ2000Eq)")
    axA.set_ylabel("y  ($10^3$ km)")
    lim = 1.18 * r_moon
    axA.set_xlim(-lim, lim)
    axA.set_ylim(-lim, lim)

    # ---------- (b) Moon-centred capture ----------
    rm = np.linalg.norm(sat_m, axis=1)
    near = rm < 1.15 * MOON_SOI_KM
    xm, ym = sat_m[near, 0], sat_m[near, 1]
    _style_axes(axB)
    axB.add_patch(plt.Circle((0, 0), MOON_SOI_KM, fill=False, ec=C_FAINT,
                             ls=(0, (5, 5)), lw=1.0, alpha=0.8, zorder=2))
    axB.annotate("SOI", (0, MOON_SOI_KM), textcoords="offset points",
                 xytext=(6, -12), color=C_TEXT, fontsize=8, alpha=0.8)
    _glow(axB, xm, ym, C_CAPTURE, lw=1.5, zorder=3)
    _disk(axB, 0, 0, MOON_RADIUS_KM, C_MOON, zorder=8)
    if near.any():
        axB.scatter([xm[0]], [ym[0]], s=24, color=C_TEXT, edgecolors="white",
                    lw=0.6, zorder=9)
        axB.annotate("SOI entry", (xm[0], ym[0]), textcoords="offset points",
                     xytext=(8, 6), color=C_TEXT, fontsize=8)
    axB.set_title("(b)  Moon-centred: binary-QUBO braking at the lunar encounter",
                  color=C_TEXT, fontsize=10.5, pad=8)
    axB.set_xlabel("x  (km, Moon MJ2000Eq)")
    axB.set_ylabel("y  (km)")
    s = 1.18 * MOON_SOI_KM
    axB.set_xlim(-s, s)
    axB.set_ylim(-s, s)

    fig.tight_layout(pad=1.4)
    out = FIG_DIR / "smart1_trajectory.png"
    fig.savefig(out, dpi=200, facecolor=C_BG, bbox_inches="tight")
    print(f"  figure written to {out}")
    print(f"  spiral days {days[enc]:.1f} to encounter; "
          f"{int(near.sum())} ephemeris points near the Moon")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--replot", action="store_true",
                    help="regenerate the figure from the cached ephemeris (no GMAT)")
    args = ap.parse_args()

    cache = FIG_DIR / "smart1_trajectory.npz"
    if args.replot:
        if not cache.exists():
            raise SystemExit(f"{cache} not found; run once without --replot first.")
        data = np.load(cache)["ephem"]
    else:
        data = _generate_ephemeris()
        FIG_DIR.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(cache, ephem=data)
        print(f"  ephemeris cached to {cache}  ({data.shape[0]} points)")

    _plot(data)


if __name__ == "__main__":
    main()
